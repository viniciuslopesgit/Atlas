import Foundation

/// A secret that used to be hardcoded in `environment { variables = { … } }` of an imported resource.
/// The value is kept in the Keychain and passed to terraform as TF_VAR_<tfVarName>; it is never written to disk.
struct StackEnvVar: Codable, Hashable, Identifiable, Sendable {
    var id = UUID().uuidString
    var tfVarName: String
    var envKey: String
    var value: String
    var resourceType: String
    var resourceName: String
    var sourceFile: String

    enum CodingKeys: String, CodingKey { case id, tfVarName, envKey, resourceType, resourceName, sourceFile }

    init(id: String = UUID().uuidString, tfVarName: String, envKey: String, value: String,
         resourceType: String, resourceName: String, sourceFile: String) {
        self.id = id
        self.tfVarName = tfVarName
        self.envKey = envKey
        self.value = value
        self.resourceType = resourceType
        self.resourceName = resourceName
        self.sourceFile = sourceFile
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        tfVarName = try c.decode(String.self, forKey: .tfVarName)
        envKey = try c.decode(String.self, forKey: .envKey)
        resourceType = try c.decode(String.self, forKey: .resourceType)
        resourceName = try c.decode(String.self, forKey: .resourceName)
        sourceFile = try c.decode(String.self, forKey: .sourceFile)
        value = ""
    }
}

/// Two passes over the project's .tf files (ported from Atlas 1.0.1):
/// collect hardcoded `environment.variables` values, then replace them with `var.<name>` references
/// and declare those variables as sensitive. Values stay out of the files.
enum EnvVarExtractor {
    /// Atlas 1.0.1 wrote `variables.tf`; a dedicated file keeps the user's own variables.tf untouched.
    static let variablesFile = "atlas_env_variables.tf"

    private struct Occurrence {
        let key, value, resourceType, resourceName, file: String
    }

    static func extractAndReplace(in project: URL) throws -> [StackEnvVar] {
        let files = try FileManager.default.contentsOfDirectory(at: project, includingPropertiesForKeys: nil)
            .filter { $0.pathExtension == "tf" && $0.lastPathComponent != variablesFile }
            .sorted { $0.lastPathComponent < $1.lastPathComponent }
        var contents: [URL: String] = [:]
        var found: [Occurrence] = []
        for f in files {
            guard let text = try? String(contentsOf: f, encoding: .utf8) else { continue }
            contents[f] = text
            found += collect(text, file: f.lastPathComponent)
        }
        guard !found.isEmpty else { return [] }

        let names = varNames(found)
        for f in files {
            guard let text = contents[f] else { continue }
            let replaced = replace(text, names)
            if replaced != text { try Data(replaced.utf8).write(to: f, options: .atomic) }
        }

        var seen: Set<String> = []
        var vars: [StackEnvVar] = []
        for o in found where seen.insert("\(o.key)\u{0}\(o.value)").inserted {
            vars.append(StackEnvVar(tfVarName: names["\(o.key)\u{0}\(o.value)"]!, envKey: o.key, value: o.value,
                                    resourceType: o.resourceType, resourceName: o.resourceName, sourceFile: o.file))
        }
        try writeVariables(vars, in: project)
        return vars
    }

    /// Declarations only — no values on disk.
    static func writeVariables(_ vars: [StackEnvVar], in project: URL) throws {
        var s = """
        # Generated by Atlas — do not edit manually.
        # Environment variables extracted from imported Terraform resources.
        # Values are stored in the macOS Keychain and passed to terraform as TF_VAR_* when Atlas runs it.


        """
        for v in vars.sorted(by: { $0.tfVarName < $1.tfVarName }) {
            s += """
            variable "\(v.tfVarName)" {
              description = \(HclGenerator.quote("\(v.envKey) for \(v.resourceType).\(v.resourceName)"))
              type        = string
              sensitive   = true
              default     = null
            }


            """
        }
        try Data(s.utf8).write(to: project.appendingPathComponent(variablesFile), options: .atomic)
    }

    // MARK: Passes

    /// Walks a file tracking resource → environment → variables nesting and calls `visit` for each
    /// `KEY = "value"` line inside `variables = {}`. `visit` returns a replacement line, or nil to keep it.
    private static func walk(_ content: String, visit: (_ line: String, _ key: String, _ value: String,
                                                       _ type: String, _ name: String) -> String?) -> String {
        var out: [String] = []
        var type: String?, name: String?
        var depth = 0
        var inEnv = false, inVars = false
        for raw in content.components(separatedBy: "\n") {
            let t = HclLine.trimmedStart(raw)
            let net = HclLine.depth(raw)
            let previous = depth
            depth = max(0, depth + net)
            if net < 0 {
                if inVars && depth < 3 { inVars = false }
                if inEnv && depth < 2 { inEnv = false }
                if depth == 0 { type = nil; name = nil }
                out.append(raw)
                continue
            }
            if net == 0 {
                if depth == 3, inVars, let type, let name,
                   let m = t.firstMatch(#"^(\w+)\s*=\s*"([^"]*)"\s*$"#) {
                    let key = String(m[1]), value = String(m[2])
                    if !value.trimmingCharacters(in: .whitespaces).isEmpty, !value.hasPrefix("var."),
                       let replacement = visit(raw, key, value, type, name) {
                        out.append(replacement)
                        continue
                    }
                }
                out.append(raw)
                continue
            }
            switch previous {
            case 0:
                if let m = t.firstMatch(#"^resource\s+"([^"]+)"\s+"([^"]+)""#) { type = String(m[1]); name = String(m[2]) }
            case 1:
                if !inEnv, t.trimmingCharacters(in: CharacterSet(charactersIn: " \t{")) == "environment" { inEnv = true }
            case 2:
                if inEnv, !inVars, t.hasPrefix("variables"), t.contains("=") { inVars = true }
            default: break
            }
            out.append(raw)
        }
        return out.joined(separator: "\n")
    }

    private static func collect(_ content: String, file: String) -> [Occurrence] {
        var found: [Occurrence] = []
        _ = walk(content) { _, key, value, type, name in
            found.append(Occurrence(key: key, value: value, resourceType: type, resourceName: name, file: file))
            return nil
        }
        return found
    }

    /// One variable per key when every resource uses the same value; otherwise one per resource.
    private static func varNames(_ found: [Occurrence]) -> [String: String] {
        var map: [String: String] = [:]
        for (key, group) in Dictionary(grouping: found, by: \.key) {
            let values = Set(group.map(\.value))
            for o in group where map["\(key)\u{0}\(o.value)"] == nil {
                map["\(key)\u{0}\(o.value)"] = values.count == 1 ? tfName(key) : tfName("\(o.resourceName)_\(key)")
            }
        }
        return map
    }

    private static func replace(_ content: String, _ names: [String: String]) -> String {
        walk(content) { raw, key, value, _, _ in
            guard let name = names["\(key)\u{0}\(value)"], let eq = raw.firstIndex(of: "=") else { return nil }
            return String(raw[..<eq]) + "= var." + name
        }
    }

    static func tfName(_ s: String) -> String {
        s.lowercased().replacingMatches(#"[^a-z0-9]+"#, with: "_").trimmingCharacters(in: CharacterSet(charactersIn: "_"))
    }
}
