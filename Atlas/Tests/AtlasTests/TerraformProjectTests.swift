import Foundation
import Testing
@testable import Atlas

struct TerraformProjectTests {
    private func tempDir(_ prefix: String) throws -> URL {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("\(prefix)-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }

    @Test func storeRoundTripsProjectsAndActiveProject() throws {
        let folder = try tempDir("store")
        let project = try tempDir("proj")
        let store = TerraformProjectStore(folder: folder)
        #expect(store.load() == .init())
        #expect(store.activeProject == nil)

        let p = TerraformProject(name: "infra", path: project.path)
        store.save(.init(projects: [p], activeId: p.id))
        #expect(store.load().projects.map(\.id) == [p.id] && store.load().projects.first?.path == p.path)
        #expect(store.activeProject?.id == p.id)

        try FileManager.default.removeItem(at: project)
        #expect(store.activeProject == nil, "a deleted folder is not an active project")
    }

    @Test @MainActor func emptyFolderGetsTheAwsProvider() throws {
        let dir = try tempDir("scaffold")
        IaCModel.scaffoldIfEmpty(dir)
        let providers = try String(contentsOf: dir.appendingPathComponent("providers.tf"), encoding: .utf8)
        #expect(providers.contains("source  = \"hashicorp/aws\""))
        #expect(!providers.contains("access_key"), "credentials only ever come from the environment")

        let other = try tempDir("existing")
        try "# mine\n".write(to: other.appendingPathComponent("main.tf"), atomically: true, encoding: .utf8)
        IaCModel.scaffoldIfEmpty(other)
        #expect(!FileManager.default.fileExists(atPath: other.appendingPathComponent("providers.tf").path))
    }

    @Test func adoptWritesTemplatesAndImportBlocksOnce() throws {
        let dir = try tempDir("adopt")
        var options = CreateBucketOptions()
        options.bucketName = "acme-logs"
        options.versioningEnabled = true
        options.tags = [("team", "data")]
        let bucket = TerraformAware.bucket(options)
        let vpc = ImportDiscovery.resource(.vpc, awsId: "vpc-1", name: "main", tfName: "main", importId: "vpc-1", region: "us-east-1")

        let files = try TerraformAware.adopt([bucket, vpc], into: dir).map(\.lastPathComponent)
        #expect(Set(files) == ["s3.tf", "imports.tf"])
        let s3 = try String(contentsOf: dir.appendingPathComponent("s3.tf"), encoding: .utf8)
        #expect(s3.contains("resource \"aws_s3_bucket\" \"acme_logs\""))
        #expect(s3.contains("\"team\" = \"data\""))

        // Adopting again adds nothing new to imports.tf.
        try TerraformAware.adopt([bucket], into: dir)
        let imports = try String(contentsOf: dir.appendingPathComponent("imports.tf"), encoding: .utf8)
        #expect(imports.components(separatedBy: "to = aws_s3_bucket.acme_logs").count == 2)
        #expect(imports.contains("to = aws_vpc.main\n  id = \"vpc-1\""))

        // A new resource is appended after the existing blocks, without a second header.
        let sg = ImportDiscovery.resource(.securityGroup, awsId: "sg-9", name: "web", tfName: "web", importId: "sg-9", region: "us-east-1")
        try TerraformAware.adopt([sg], into: dir)
        let after = try String(contentsOf: dir.appendingPathComponent("imports.tf"), encoding: .utf8)
        #expect(after.hasPrefix(imports))
        #expect(after.contains("to = aws_security_group.web"))
        #expect(after.components(separatedBy: "Import blocks generated by Atlas").count == 2)
    }

    @Test func ec2TemplateKeepsTheRealNameTag() {
        var m = Ec2InstanceHcl()
        m.resourceName = "web_server"
        m.nameTag = "Web Server"
        #expect(HclGenerator.ec2Instance(m).contains("Name      = \"Web Server\""))
        m.nameTag = nil
        #expect(HclGenerator.ec2Instance(m).contains("Name      = \"web_server\""))
    }
}
